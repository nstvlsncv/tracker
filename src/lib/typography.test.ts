import { describe, expect, it } from 'vitest'
import { tidy } from './typography'

const N = ' '

describe('висячие предлоги', () => {
  it('короткое слово склеивается со следующим', () => {
    expect(tidy('Задачи по дням с понедельника')).toBe(`Задачи по${N}дням с${N}понедельника`)
  })

  it('два коротких слова подряд склеиваются оба', () => {
    expect(tidy('Отмечай и не пропускай')).toBe(`Отмечай и${N}не${N}пропускай`)
  })

  it('слово в начале строки и после кавычки тоже', () => {
    expect(tidy('В трекере «на завтра»')).toBe(`В${N}трекере «на${N}завтра»`)
  })

  it('длинные слова и части слов не трогает', () => {
    expect(tidy('Неделя целиком')).toBe('Неделя целиком')
    expect(tidy('Трекер помогает')).toBe('Трекер помогает')
  })
})
