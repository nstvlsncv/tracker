/** Короткие слова, которые не должны оставаться в конце строки: предлоги, союзы, частицы. */
const SHORT_WORDS = [
  'а', 'в', 'и', 'к', 'о', 'с', 'у', 'я',
  'во', 'до', 'за', 'из', 'ко', 'на', 'не', 'ни', 'но', 'об', 'от', 'по', 'со', 'то', 'ты',
  'без', 'для', 'или', 'как', 'над', 'под', 'при', 'про', 'что', 'это', 'его', 'она', 'они',
]

const NBSP = ' '
// Слово целиком (перед ним начало строки, пробел, скобка или кавычка) и обычный пробел после него.
const HANGING = new RegExp(`(^|[\\s(«„"${NBSP}])(${SHORT_WORDS.join('|')}) `, 'giu')

/**
 * Убирает висячие предлоги: пробел после короткого слова становится неразрывным, и слово
 * переносится на следующую строку вместе с тем, к чему относится. Работает при любой ширине
 * экрана, потому что перенос запрещён в самом тексте, а не подобран под конкретную вёрстку.
 */
export function tidy(text: string): string {
  // Два прохода: в «и в саду» после замены первого слова второе уже не начинается с пробела.
  return text.replace(HANGING, `$1$2${NBSP}`).replace(HANGING, `$1$2${NBSP}`)
}
